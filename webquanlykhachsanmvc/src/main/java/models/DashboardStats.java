package models;

public class DashboardStats {

    private double doanhThu;
    private int tongBooking;
    private int phongTrong;
    private int phongDat;
    private int tongKH;

    public double getDoanhThu() {
        return doanhThu;
    }

    public void setDoanhThu(double doanhThu) {
        this.doanhThu = doanhThu;
    }

    public int getTongBooking() {
        return tongBooking;
    }

    public void setTongBooking(int tongBooking) {
        this.tongBooking = tongBooking;
    }

    public int getPhongTrong() {
        return phongTrong;
    }

    public void setPhongTrong(int phongTrong) {
        this.phongTrong = phongTrong;
    }

    public int getPhongDat() {
        return phongDat;
    }

    public void setPhongDat(int phongDat) {
        this.phongDat = phongDat;
    }

    public int getTongKH() {
        return tongKH;
    }

    public void setTongKH(int tongKH) {
        this.tongKH = tongKH;
    }
}